/**
 * Interface language.
 *
 * Deliberately NOT the language being learned: a French speaker studying
 * Spanish wants a French interface and Spanish content. This only ever touches
 * the app's own words — lessons, corrections and conversations stay in whatever
 * language the teacher is teaching.
 */
/**
 * A UI language is any registered locale code (Sprint 10.5 — i18n).
 * Widened from a fixed union to a string so new languages can be ADDED as
 * resources without changing this engine.
 */
export type Locale = string;

/** A registered UI language: code, display name, and a (possibly partial)
 *  catalog. Partial is fine — missing keys fall back to English, so a language
 *  can ship at any coverage and still work. Adding a language = one
 *  `registerLocale` call from a resource file; the engine below never changes. */
export interface LocaleEntry {
  code: Locale;
  name: string;
  catalog: Partial<Record<string, string>>;
}

const registry = new Map<Locale, LocaleEntry>();

/** Register (or replace) a UI language. Call from a locale resource module. */
export function registerLocale(
  code: Locale,
  name: string,
  catalog: Partial<Record<string, string>>,
): void {
  registry.set(code, { code, name, catalog });
}

/** All registered locale codes, English first. */
export function supportedLocaleCodes(): Locale[] {
  return [...registry.keys()];
}

/** Display name for a locale code (falls back to the code). */
export function localeName(code: Locale): string {
  return registry.get(code)?.name ?? code;
}

