for (const locale of learningDataControlAfricaLocales) {
  const values = learningDataControlAfricaValues[locale];
  if (values.length !== learningDataControlAfricaKeys.length) {
    throw new Error(`Incomplete learning-data control locale: ${locale}`);
  }
  extendLocale(locale, Object.fromEntries(
    learningDataControlAfricaKeys.map((key, index) => [key, values[index]!] as const),
  ));
}
